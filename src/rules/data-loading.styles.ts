export type Sweep = "still" | "armed" | "run";
export type Signal = "offline" | "connecting" | "online";

const cls = (...items: stylex.StyleXArray<stylex.CompiledStyles | false>[]) =>
  stylex.attrs(...items).class ?? "";

/** Classes the demos' first frame and their elements both set, so they have one source. */
export const view = {
  ctlButton: cls(button.base, buttonVariant["primary-neutral"], button.sm, styles.ctlButton),
  spin: (small: boolean, inFigure = false) =>
    cls(styles.spin, small && styles.spinSmall, inFigure && styles.spinInFigure),
  paint: (sweep: Sweep) =>
    cls(styles.paint, sweep === "armed" && styles.paintArmed, sweep === "run" && styles.paintRun),
  cover: (sweep: Sweep) =>
    cls(styles.cover, sweep !== "still" && styles.coverShown, sweep === "run" && styles.coverRun),
  amount: (fresh: boolean) => cls(styles.amount, fresh && styles.amountFresh),
  sub: (blank: boolean) => cls(styles.sub, blank && styles.hidden),
  mailRow: (skeleton: boolean) => cls(styles.mailRow, skeleton && styles.mailRowStill),
  avatar: (skeleton: boolean) => cls(styles.avatar, skeleton && styles.bone),
  mailText: cls(styles.mailText),
  mailFrom: (skeleton: boolean) =>
    cls(styles.mailLine, styles.mailFrom, skeleton && styles.bone),
  mailSubject: (skeleton: boolean) =>
    cls(styles.mailLine, styles.mailSubject, skeleton && styles.bone),
  signal: (signal: Signal) =>
    cls(
      styles.status,
      signal === "offline" && styles.offline,
      signal === "online" && styles.online,
    ),
  balance: (online: boolean, careful: boolean) =>
    cls(
      styles.balanceValue,
      online && !careful && styles.balanceJump,
      !online && careful && styles.balanceWait,
    ),
  histRow: (fresh: boolean) => cls(styles.histRow, fresh && styles.histRowNew),
  histAmount: cls(styles.histAmount),
  time: cls(styles.time),
};
