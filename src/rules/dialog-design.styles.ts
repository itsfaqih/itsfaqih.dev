// The classes the demos' elements (dialog-design.client.ts) switch between, so the first frame
// and the client build them from one place.
export const dialogView = (top: boolean, open: boolean) =>
  stylex.attrs(styles.dialog, top && styles.dialogTop, open && styles.dialogOpen).class ?? "";
export const scrimView = (top: boolean, on: boolean) =>
  stylex.attrs(styles.scrim, top && styles.scrimTop, on && styles.scrimOn).class ?? "";
export const readView = (tone: ReadTone) =>
  stylex.attrs(styles.read, tone === "no" && styles.readNo, tone === "yes" && styles.readYes)
    .class ?? "";
export const cardView = (gone: boolean) =>
  stylex.attrs(styles.spread, styles.card, gone && styles.gone).class ?? "";
export const articleView = (locked: boolean) =>
  stylex.attrs(styles.page, styles.article, locked && styles.locked).class ?? "";
// The ring shares no property with a stop's own look, so it joins that look's classes as is.
export const ringView = (behind: boolean) =>
  stylex.attrs(styles.ring, behind && styles.ringBehind).class ?? "";

