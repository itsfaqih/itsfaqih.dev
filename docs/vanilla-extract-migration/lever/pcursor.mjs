import { createRequire } from "node:module";
import http from "node:http"; import fs from "node:fs"; import path from "node:path";
const require = createRequire(process.cwd() + "/x.js");
const { chromium } = require("playwright");
const [base, next, runs = "5"] = process.argv.slice(2);
const MIME = { html: "text/html", js: "text/javascript", css: "text/css", svg: "image/svg+xml", png: "image/png", woff2: "font/woff2" };
const serve = (dir) => new Promise((res) => { const s = http.createServer((q, r) => { let p = decodeURIComponent(q.url.split("?")[0]); if (p === "/") p = "/index.html"; let f = path.join(dir, p); if (!fs.existsSync(f) && fs.existsSync(f + ".html")) f += ".html"; if (!fs.existsSync(f)) { r.writeHead(404); return r.end(); } r.writeHead(200, { "content-type": MIME[f.split(".").pop()] || "application/octet-stream" }); r.end(fs.readFileSync(f)); }); s.listen(0, "127.0.0.1", () => res(s)); });
const sa = await serve(base), sb = await serve(next);
const urls = { base: `http://127.0.0.1:${sa.address().port}/`, new: `http://127.0.0.1:${sb.address().port}/` };
const browser = await chromium.launch();
const state = (page) => page.evaluate(() => { const c = document.querySelector("body>div>i")?.parentElement?.closest("print-cursor") ?? document.querySelector("print-cursor"); return { cls: c?.className.split(/\s+/).filter((x) => x === "on" || x === "down").join("+"), mode: c?.dataset.mode, vis: c ? getComputedStyle(c).visibility : null, tag: c?.tagName }; });
const out = { base: [], new: [] };
for (let i = 0; i < +runs; i++) for (const k of i % 2 ? ["new", "base"] : ["base", "new"]) for (const width of [1440, 959]) {
  const ctx = await browser.newContext({ viewport: { width, height: 900 }, colorScheme: "dark", hasTouch: false });
  await ctx.addInitScript(() => { try { sessionStorage.setItem("intro-seen", "1"); } catch {} });
  const page = await ctx.newPage();
  await page.goto(urls[k], { waitUntil: "load" });
  await page.waitForTimeout(600);
  const l = page.locator("[aria-expanded='false']:not(header *)").first();
  await l.scrollIntoViewIfNeeded();
  const box = await l.boundingBox();
  await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2, { steps: 4 });
  await page.waitForTimeout(120);
  const hover = await state(page);
  const under = await page.evaluate(([x, y]) => { const e = document.elementFromPoint(x, y); return { tag: e?.tagName, cursor: e ? getComputedStyle(e).cursor : null }; }, [box.x + box.width / 2, box.y + box.height / 2]);
  await page.mouse.down(); await page.mouse.up(); await page.waitForTimeout(120);
  const after = await state(page);
  out[k].push(`${width} hover ${hover.cls}/${hover.mode}/${hover.vis} under ${under.tag}/${under.cursor} after ${after.cls}/${after.mode}/${after.vis}`);
  await ctx.close();
}
await browser.close(); sa.close(); sb.close();
for (const k of ["base", "new"]) console.log(k + "\n  " + out[k].join("\n  "));
